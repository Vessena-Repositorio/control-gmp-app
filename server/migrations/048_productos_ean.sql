--
-- Entran solo los 419 productos con UN solo EAN 14. Quedaron afuera 26 con
-- datos contradictorios -dos EAN 14 distintos, o el mismo EAN 14 en dos
-- productos-, que Claudia hace corregir en el ERP: cargar un codigo dudoso
-- seria peor que no mostrar ninguno, porque la analista lo usa para comparar
-- contra la caja.
--
-- La tabla se puede volver a cargar cuando el ERP este corregido: el UPSERT
-- actualiza por codigo.

