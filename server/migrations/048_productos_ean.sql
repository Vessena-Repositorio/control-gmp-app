-- Codigo de producto -> EAN 14 de la caja
-- ============================================================================
--
-- Pedido de Claudia (25/09/2026): al controlar, la analista tiene que ver el
-- EAN 14 que corresponde al producto, y tambien quien aprueba. Se usa en
-- Control en proceso (campo codPT de cada control) y en Fabuloso (codigo_pt
-- del muestreo).
--
-- Los datos salen del export del ERP (Export_M_Product.csv, 3246 productos):
-- de cada producto se toma el codigo de barras de 14 digitos, que es el de la
